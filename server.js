const readline = require('node:readline');
const { randomUUID } = require('node:crypto');
const { MongoClient, MongoError } = require('mongodb');
const { listLanguages, fetchTranscript } = require('youtube-transcript-plus');

const app = express();
const PORT = Number(process.env.PORT) || 3000;
const HOST = '127.0.0.1';
const TRANSCRIPTS_DIR = path.join(__dirname, 'transcripts');
const MONGODB_URI = process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017';
const MONGODB_DATABASE = 'lang';
const ALIGNMENT_PYTHON = path.join(__dirname, '.venv', 'Scripts', 'python.exe');
const ALIGNMENT_SCRIPT = path.join(__dirname, 'scripts', 'align_words.py');
const VIDEO_ID_PATTERN = /^[A-Za-z0-9_-]{11}$/;
const mongoClient = new MongoClient(MONGODB_URI, { serverSelectionTimeoutMS: 30000 });
let transcriptCollection;
let migrationCollection;
const wordJobs = new Map();
let activeWordJobId = null;

app.use(express.json({ limit: '10mb' }));
app.use(express.static(path.join(__dirname, 'public')));

function extractVideoId(input) {
  let url;
  try {
    url = new URL(input);
  } catch {
    const error = new Error('Masukkan URL YouTube yang valid.');
    error.status = 400;
    throw error;
  }

  const hostname = url.hostname.toLowerCase().replace(/^www\./, '');
  let videoId;
  if (hostname === 'youtu.be') {
    videoId = url.pathname.split('/').filter(Boolean)[0];
  } else if (hostname === 'youtube.com' || hostname === 'm.youtube.com') {
    if (url.pathname === '/watch') {
      videoId = url.searchParams.get('v');
    } else {
      videoId = url.pathname.match(/^\/(?:shorts|embed|live)\/([^/]+)/)?.[1];
    }
  }

  if (!videoId || !VIDEO_ID_PATTERN.test(videoId)) {
    const error = new Error('URL harus mengarah ke video YouTube yang valid.');
    error.status = 400;
    throw error;
  }
  return videoId;
}

function validateVideoId(videoId) {
  if (!VIDEO_ID_PATTERN.test(videoId)) {
    const error = new Error('ID video tidak valid.');
    error.status = 400;
    throw error;
  }
  return videoId;
}

async function getCaptionLanguages(videoId) {
  let playerResponse;
  const languages = await listLanguages(videoId, {
    playerFetch: async ({ url, method, headers, body, signal }) => {
      const response = await fetch(url, { method, headers, body, signal });
      playerResponse = await response.clone().json();
      return response;
    },
  });
  const renderer =
    playerResponse?.captions?.playerCaptionsTracklistRenderer ||
    playerResponse?.playerCaptionsTracklistRenderer;
  const audioTracks = renderer?.audioTracks || [];
  const defaultCaptionTrackIndex =
    audioTracks.find((track) => track.hasDefaultTrack && Number.isInteger(track.defaultCaptionTrackIndex))
      ?.defaultCaptionTrackIndex ??
    audioTracks.find((track) => Number.isInteger(track.defaultCaptionTrackIndex))?.defaultCaptionTrackIndex;

  const uniqueLanguages = new Map();
  languages.forEach((language, index) => {
    const candidate = {
      ...language,
      isDefault: index === defaultCaptionTrackIndex,
    };
    const current = uniqueLanguages.get(language.languageCode);
    if (
      !current ||
      (candidate.isDefault && !current.isDefault) ||
      (candidate.isDefault === current.isDefault && current.isAutoGenerated && !candidate.isAutoGenerated)
    ) {
      uniqueLanguages.set(language.languageCode, candidate);
    }
  });

  const availableLanguages = [...uniqueLanguages.values()];
  const recommendedLanguage =
    availableLanguages.find((language) => language.isDefault) ||
    availableLanguages.find((language) => /^en(?:-|$)/i.test(language.languageCode)) ||
    availableLanguages.find((language) => !language.isAutoGenerated) ||
    availableLanguages[0];

  return {
    languages: availableLanguages,
    recommendedLanguage,
    recommendation:
      recommendedLanguage?.isDefault
        ? 'video-default'
        : /^en(?:-|$)/i.test(recommendedLanguage?.languageCode || '')
          ? 'english-fallback'
          : 'first-available',
    videoId,
  };
}

function transcriptError(error) {
  if (error instanceof MongoError) {
    return { status: 503, message: 'MongoDB tidak dapat menyimpan atau membaca transkrip. Pastikan layanan MongoDB berjalan.' };
  }
  if (error.name === 'YoutubeTranscriptDisabledError') {
    return { status: 404, message: 'Pemilik video menonaktifkan caption; transkrip tidak tersedia.' };
  }
  if (error.name === 'YoutubeTranscriptNotAvailableError') {
    return { status: 404, message: 'Transkrip tidak tersedia untuk video ini.' };
  }
  if (error.name === 'YoutubeTranscriptNotAvailableLanguageError') {
    return {
      status: 404,
      message: `Transkrip bahasa ${error.lang} tidak tersedia. Pilih bahasa lain dari daftar.`,
    };
  }
  if (error.name === 'YoutubeTranscriptVideoUnavailableError') {
    return { status: 404, message: 'Video tidak tersedia atau telah dihapus.' };
  }
  if (error.name === 'YoutubeTranscriptTooManyRequestError') {
    return { status: 429, message: 'YouTube membatasi permintaan sementara. Coba lagi nanti.' };
  }
  return { status: 400, message: error.message || 'Gagal mengambil transkrip.' };
}

function transcriptFromDocument(document) {
  if (!document) return null;
  const { _id, ...transcript } = document;
  return transcript;
}

async function saveTranscript(transcript) {
  await transcriptCollection.replaceOne(
    { _id: transcript.videoId },
    { ...transcript, _id: transcript.videoId },
    { upsert: true },
  );
}

async function migrateLegacyTranscripts() {
  const migrationId = 'legacy-json-transcripts-v1';
  if (await migrationCollection.findOne({ _id: migrationId })) return 0;

  let files;
  try {
    files = await fs.readdir(TRANSCRIPTS_DIR);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    files = [];
  }

  let migrated = 0;
  for (const file of files.filter((name) => name.endsWith('.json'))) {
    const transcript = JSON.parse(await fs.readFile(path.join(TRANSCRIPTS_DIR, file), 'utf8'));
    const videoId = validateVideoId(path.basename(file, '.json'));
    if (transcript.videoId !== videoId) {
      throw new Error(`ID video pada file legacy ${file} tidak cocok dengan namanya.`);
    }
    const result = await transcriptCollection.updateOne(
      { _id: videoId },
      { $setOnInsert: { ...transcript, _id: videoId } },
      { upsert: true },
    );
    migrated += result.upsertedCount;
  }
  await migrationCollection.updateOne(
    { _id: migrationId },
    { $setOnInsert: { completedAt: new Date().toISOString() } },
    { upsert: true },
  );
  return migrated;
}

function updateWordJob(jobId, update) {
  const job = wordJobs.get(jobId);
  if (job) Object.assign(job, update, { updatedAt: new Date().toISOString() });
}

async function runWordAlignment(jobId, transcript) {
  const jobDirectory = path.join(os.tmpdir(), 'lang-alignment-jobs', jobId);
  try {
    await fs.mkdir(jobDirectory, { recursive: true });
    updateWordJob(jobId, { state: 'running', progress: 1, stage: 'starting', message: 'Menyiapkan audio dan caption...' });
    const child = spawn(ALIGNMENT_PYTHON, [ALIGNMENT_SCRIPT], {
      windowsHide: true,
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    let result;
    let stderr = '';
    const lines = readline.createInterface({ input: child.stdout });
    lines.on('line', (line) => {
      try {
        const event = JSON.parse(line);
        if (event.type === 'progress') {
          updateWordJob(jobId, {
            progress: Math.max(1, Math.min(99, Number(event.progress) || 1)),
            stage: event.stage || 'processing',
            message: event.message || 'Memproses audio...',
          });
        } else if (event.type === 'result') {
          result = event;
        } else if (event.type === 'error') {
          updateWordJob(jobId, { error: event.message });
        }
      } catch {
        console.error('Output worker alignment tidak valid:', line);
      }
    });
    child.stderr.on('data', (chunk) => {
      stderr = `${stderr}${chunk.toString()}`.slice(-8000);
    });

    const processResult = new Promise((resolve, reject) => {
      child.once('error', reject);
      child.once('close', (code) => resolve(code));
    });
    child.stdin.end(JSON.stringify({
      url: transcript.url,
      language: transcript.language.code,
      segments: transcript.sourceCaptions || transcript.segments,
      outputDir: jobDirectory,
    }));

    const exitCode = await processResult;
    if (exitCode !== 0 || !result) {
      const error = wordJobs.get(jobId)?.error;
      throw new Error(error || stderr.trim().split(/\r?\n/).at(-1) || 'Penyelarasan kata gagal.');
    }

    transcript.sourceCaptions = transcript.sourceCaptions || transcript.segments;
    transcript.segments = result.words;
    transcript.granularity = 'word';
    transcript.alignment = {
      engine: 'WhisperX forced alignment',
      language: result.language,
      alignedWords: result.words.length,
      unalignedWords: result.unalignedWords,
      completedAt: new Date().toISOString(),
    };
    transcript.updatedAt = new Date().toISOString();
    await saveTranscript(transcript);
    const unalignedWords = Number(result.unalignedWords) || 0;
    const completionMessage = `${result.words.length.toLocaleString('id-ID')} kata berhasil diselaraskan.${unalignedWords ? ` ${unalignedWords.toLocaleString('id-ID')} kata tidak mendapatkan timestamp dan tidak ditampilkan.` : ''}`;
    updateWordJob(jobId, {
      state: 'completed',
      progress: 100,
      stage: 'completed',
      message: completionMessage,
      result: { videoId: transcript.videoId, wordCount: result.words.length },
    });
  } catch (error) {
    console.error('Gagal membuat timestamp per kata:', error);
    updateWordJob(jobId, {
      state: 'failed',
      stage: 'failed',
      message: error.message || 'Penyelarasan kata gagal.',
      error: error.message || 'Penyelarasan kata gagal.',
    });
  } finally {
    await fs.rm(jobDirectory, { recursive: true, force: true }).catch((error) => {
      console.error('Gagal membersihkan audio sementara:', error);
    });
    if (activeWordJobId === jobId) activeWordJobId = null;
  }
}

app.post('/api/languages', async (req, res) => {
  try {
    const videoId = extractVideoId(req.body?.url);
    const result = await getCaptionLanguages(videoId);
    if (!result.languages.length) {
      return res.status(404).json({ error: 'Caption tidak tersedia untuk video ini.' });
    }
    res.json(result);
  } catch (error) {
    console.error('Gagal mencari bahasa caption:', error);
    const { status, message } = transcriptError(error);
    res.status(status).json({ error: message });
  }
});

app.post('/api/process', async (req, res) => {
  try {
    const videoId = extractVideoId(req.body?.url);
    const videoUrl = `https://www.youtube.com/watch?v=${videoId}`;
    const { languages } = await getCaptionLanguages(videoId);
    if (!languages.length) {
      return res.status(404).json({ error: 'Caption tidak tersedia untuk video ini.' });
    }
    const requestedLanguage = String(req.body?.languageCode || '');
    const selectedLanguage = languages.find((language) => language.languageCode === requestedLanguage);
    if (!selectedLanguage) {
      return res.status(400).json({ error: 'Pilih bahasa caption yang tersedia untuk video ini.' });
    }
    const result = await fetchTranscript(videoId, {
      lang: selectedLanguage.languageCode,
      videoDetails: true,
    });

    const transcript = {
      videoId,
      title: result.videoDetails.title,
      duration: result.videoDetails.lengthSeconds,
      url: videoUrl,
      language: {
        code: selectedLanguage.languageCode,
        name: selectedLanguage.languageName,
        isAutoGenerated: selectedLanguage.isAutoGenerated,
      },
      thumbnailUrl:
        result.videoDetails.thumbnails.at(-1)?.url ||
        `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`,
      generatedAt: new Date().toISOString(),
      segments: result.segments.map((segment) => ({
        start: Number(segment.offset.toFixed(3)),
        end: Number((segment.offset + segment.duration).toFixed(3)),
        text: segment.text,
      })),
    };
    transcript.sourceCaptions = transcript.segments;

    await saveTranscript(transcript);
    res.json(transcript);
  } catch (error) {
    console.error('Gagal memproses transkrip:', error);
    const { status, message } = transcriptError(error);
    res.status(status).json({ error: message });
  }
});

app.post('/api/transcripts/:videoId/align-words', async (req, res) => {
  try {
    if (req.body?.authorized !== true) {
      return res.status(403).json({ error: 'Konfirmasi izin memproses audio diperlukan.' });
    }
    if (!(await fs.access(ALIGNMENT_PYTHON).then(() => true, () => false))) {
      return res.status(503).json({
        error: 'WhisperX belum terpasang. Jalankan npm run setup:alignment terlebih dahulu.',
      });
    }
    const videoId = validateVideoId(req.params.videoId);
    const storedTranscript = await transcriptCollection.findOne({ _id: videoId });
    if (!storedTranscript) return res.status(404).json({ error: 'Transkrip tidak ditemukan.' });
    const transcript = transcriptFromDocument(storedTranscript);
    if (extractVideoId(transcript.url) !== transcript.videoId) {
      return res.status(400).json({ error: 'URL video pada data transkrip tidak valid.' });
    }
    if (activeWordJobId) {
      return res.status(409).json({ error: 'Penyelarasan lain sedang berjalan. Tunggu hingga selesai.' });
    }

    const captions = transcript.sourceCaptions || transcript.segments;
    if (!Array.isArray(captions) || !captions.length) {
      return res.status(422).json({ error: 'Caption sumber kosong; tidak dapat menyelaraskan kata.' });
    }
    const jobId = randomUUID();
    const job = {
      id: jobId,
      videoId: transcript.videoId,
      state: 'queued',
      stage: 'queued',
      progress: 0,
      message: 'Antrean penyelarasan dibuat.',
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };
    wordJobs.set(jobId, job);
    activeWordJobId = jobId;
    runWordAlignment(jobId, transcript);
    res.status(202).json({ jobId, state: job.state });
  } catch (error) {
    const status = error.status || (error.code === 'ENOENT' ? 404 : 500);
    res.status(status).json({ error: error.message || 'Gagal memulai penyelarasan.' });
  }
});

app.get('/api/jobs/:jobId', (req, res) => {
  const job = wordJobs.get(req.params.jobId);
  if (!job) return res.status(404).json({ error: 'Pekerjaan tidak ditemukan atau server telah dimulai ulang.' });
  const { id, videoId, state, stage, progress, message, error, result, createdAt, updatedAt } = job;
  res.json({ id, videoId, state, stage, progress, message, error, result, createdAt, updatedAt });
});

